# This script calculates weekly sales earnings.
# It asks the user for their name and sales amount.

name = input("What is your name? ")
sales = float(input("Enter your weekly sales amount in dollars: "))

if sales >= 1000:
    bonus = sales * 0.10
    print("Congratulations,", name)
    print("You earned a 10% bonus!")
else:
    bonus = 0
    print("Hello,", name)
    print("Keep working toward your sales target!")

print("Your weekly sales were $", sales)
print("Your bonus is $", bonus)

